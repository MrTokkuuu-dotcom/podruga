LANGS = ("## Языки\n{user} говорит по-русски, по-английски и по-корейски и вставляет английские названия "
         "(Valorant, Discord, YouTube) — понимай их как есть. Отвечай на языке его последней фразы. "
         "Одна фраза — один язык. Эмоции в {{}} и команды << >> всегда пиши по-русски.")

HINTS = {
    "en": "(Он сказал это по-английски — ответь ПО-АНГЛИЙСКИ. Эмоция в {} — по-русски.)",
    "ko": "(Он сказал это по-корейски — ответь ПО-КОРЕЙСКИ, просто, на «반말», как близкая подруга. Эмоция в {} — по-русски.)",
}


def stable_system(character: str, traits: str, memory: str, user: str) -> str:
    """Часть подсказки, которая не меняется от фразы к фразе: её модель считает один раз и держит в кэше."""
    return "\n".join([character.strip(), "",
                      f"## Твой характер сейчас (настройки {user})", traits.strip(), "",
                      LOCAL_RULES.format(user=user), "",
                      LANGS.format(user=user), "",
                      f"## Память о {user}", memory.strip() or "(пока пусто)"])


def turn_text(text: str, lang: str, fresh: str) -> str:
    """Последнее сообщение: свежее (время, события, чем занят) + приписка про язык + сама фраза."""
    parts = [fresh.strip()] if fresh and fresh.strip() else []
    if lang in HINTS:
        parts.append(HINTS[lang])
    parts.append(text)
    return "\n\n".join(parts[:-1]) + ("\n" if len(parts) > 1 else "") + parts[-1]
